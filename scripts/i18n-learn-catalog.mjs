// Regenerates the English "glossary" and "intros" catalogs (shared/i18n/messages/{glossary,intros}/en.ts) from
// shared/glossary.ts and shared/feature-intros.ts, the source of the words. Run after editing either file:
//   node scripts/i18n-learn-catalog.mjs
// then translate any new or changed keys in the pcm/yo/ha/ig files (tests/i18n.test.mjs lists the missing ones).
// The glossary's `term` and the intros' in-art labels, chips and values stay as they are (they're the standard
// words and pictures of app screens), so only the sentences are catalogued.
import { writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const { GLOSSARY } = await import(new URL("shared/glossary.ts", root).href);
const { FEATURE_INTROS } = await import(new URL("shared/feature-intros.ts", root).href);

export function glossaryMessages() {
  const out = {};
  for (const entry of GLOSSARY) {
    out[`${entry.key}.short`] = entry.short;
    out[`${entry.key}.example`] = entry.example;
  }
  return out;
}

export function introMessages() {
  const out = {};
  for (const intro of FEATURE_INTROS) {
    out[`${intro.key}.title`] = intro.title;
    if (intro.cta) out[`${intro.key}.cta`] = intro.cta.label;
    intro.scenes.forEach((scene, index) => {
      out[`${intro.key}.${index + 1}.caption`] = scene.caption;
      out[`${intro.key}.${index + 1}.sub`] = scene.sub;
    });
  }
  return out;
}

function file(header, messages) {
  const lines = Object.entries(messages).map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`);
  return `${header}\n// Generated by scripts/i18n-learn-catalog.mjs: edit the source file, then re-run the script.\nconst en = {\n${lines.join("\n")}\n} satisfies Record<string, string>;\n\nexport default en;\n`;
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split("/").pop())) {
  writeFileSync(new URL("shared/i18n/messages/glossary/en.ts", root), file("// Glossary meanings and examples (shared/glossary.ts), keyed \"<term key>.short\" and \"<term key>.example\".", glossaryMessages()));
  writeFileSync(new URL("shared/i18n/messages/intros/en.ts", root), file("// 60-second intro words (shared/feature-intros.ts): \"<intro>.title\", \"<intro>.cta\" and \"<intro>.<scene 1-5>.caption|sub\".", introMessages()));
  console.log("Wrote glossary/en.ts and intros/en.ts");
}
