#!/usr/bin/env node
// Lists the Rex / Peggy animation files that exist, so <Mascot> only ever requests (web) or bundles (mobile) real files.
// Run after dropping files into public/brand/mascots/anim/ (web) or apps/mobile/assets/mascots/ (mobile):
//
//   node scripts/mascots-manifest.mjs
//
// Accepted names: rex.riv, peggy.riv (one state machine called "mood" with a `mood` input), or Lottie JSON per mood:
// rex-<mood>.json, peggy-<mood>.json. Moods: idle, wave, thinking, working, celebrate, oops, sleep.
import { readdirSync, writeFileSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const MOODS = ["idle", "wave", "thinking", "working", "celebrate", "oops", "sleep"];
const VALID = new RegExp(`^(rex|peggy)(\\.riv|-(${MOODS.join("|")})\\.json)$`);
const MAX_BYTES = 150 * 1024;

function scan(dir) {
  const files = readdirSync(dir).filter((name) => VALID.test(name)).sort();
  for (const name of files) {
    const bytes = statSync(join(dir, name)).size;
    if (bytes > MAX_BYTES) console.warn(`warning: ${join(dir, name)} is ${Math.round(bytes / 1024)} KB; the spec asks for under 150 KB`);
  }
  return files;
}

const webDir = join(root, "public/brand/mascots/anim");
const web = scan(webDir);
writeFileSync(join(webDir, "mascots.json"), JSON.stringify({ files: web }, null, 2) + "\n");

const mobileDir = join(root, "apps/mobile/assets/mascots");
const mobile = scan(mobileDir);
writeFileSync(join(mobileDir, "mascots.json"), JSON.stringify({ files: mobile }, null, 2) + "\n");
// Metro needs static require() calls, so the mobile manifest also gets a generated source map.
const lines = mobile.map((name) => `  ${JSON.stringify(name)}: require(${JSON.stringify(`./${name}`)}),`);
writeFileSync(
  join(mobileDir, "index.ts"),
  `// Generated by scripts/mascots-manifest.mjs. Do not edit by hand: drop files here and re-run the script.\n` +
    `/* eslint-disable @typescript-eslint/no-require-imports */\n` +
    `export const MASCOT_ANIMATION_FILES: Record<string, unknown> = {\n${lines.join("\n")}${lines.length ? "\n" : ""}};\n`,
);
console.log(`web: ${web.length ? web.join(", ") : "no animation files"}`);
console.log(`mobile: ${mobile.length ? mobile.join(", ") : "no animation files"}`);
