"use client";

import { useRef, useState } from "react";
import { Icon } from "@/components/ui";
import { useToast } from "@/components/ui/Toast";

export function CoverImageUpload({ currentBanner, displayName, city }: { currentBanner: string | null; displayName: string; city: string }) {
  const fileRef = useRef<HTMLInputElement>(null);
  const [uploading, setUploading] = useState(false);
  const [generating, setGenerating] = useState(false);
  const { toast } = useToast();

  async function handleFile(e: React.ChangeEvent<HTMLInputElement>) {
    const file = e.target.files?.[0];
    if (!file) return;
    setUploading(true);
    const formData = new FormData();
    formData.set("banner", file);
    try {
      const res = await fetch("/api/logistics/upload-banner", { method: "POST", body: formData });
      if (res.ok) {
        toast("Cover image updated", "success");
        window.location.reload();
      } else {
        toast("Upload failed", "error");
      }
    } catch {
      toast("Upload failed", "error");
    } finally {
      setUploading(false);
    }
  }

  async function generateWithRex() {
    setGenerating(true);
    try {
      const res = await fetch("/api/logistics/generate-banner", { method: "POST" });
      if (res.ok) {
        toast("Cover generated by Rex!", "success");
        window.location.reload();
      } else {
        const data = await res.json().catch(() => ({}));
        toast(data.error || "Generation failed", "error");
      }
    } catch {
      toast("Generation failed", "error");
    } finally {
      setGenerating(false);
    }
  }

  return (
    <div style={{ height: 160, background: currentBanner ? `url(${currentBanner}) center/cover` : "linear-gradient(135deg, #5b6ad0, #3a4ba6 60%, #1f2872)", position: "relative" }}>
      <div style={{ position: "absolute", bottom: 12, left: 16, color: "white", textShadow: "0 1px 4px rgba(0,0,0,0.3)" }}>
        <div style={{ fontSize: 20, fontWeight: 700 }}>{displayName}</div>
        <div style={{ fontSize: 12, opacity: 0.85 }}>{city} · logistics partner</div>
      </div>
      <div style={{ position: "absolute", top: 10, right: 10, display: "flex", gap: 6 }}>
        <button type="button" onClick={generateWithRex} disabled={generating}
          className="dbtn dBtn-ghost" style={{ background: "rgba(255,255,255,0.9)", fontSize: 11, padding: "5px 10px" }}
        >
          {generating ? "..." : <><Icon name="sparkle" size={12} /> Rex cover</>}
        </button>
        <button type="button" onClick={() => fileRef.current?.click()} disabled={uploading}
          className="dbtn dBtn-ghost" style={{ background: "rgba(255,255,255,0.9)", fontSize: 11, padding: "5px 10px" }}
        >
          {uploading ? "..." : <><Icon name="upload" size={12} /> Change</>}
        </button>
      </div>
      <input ref={fileRef} type="file" accept="image/*" style={{ display: "none" }} onChange={handleFile} />
    </div>
  );
}
