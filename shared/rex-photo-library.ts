/**
 * Rex's photo library — the stock photos Rex offers sellers for store banners, About sections and other
 * store-editor image slots (seller onboarding "pick a photo" and the store editor's photo picker).
 *
 * Source: every photo was chosen on Unsplash (free photos only — no Unsplash+), its download was recorded through the
 * Unsplash API as their guidelines require, and a copy was stored in Shopinbos's own Supabase Storage (the public
 * `shopinbos-media` bucket, under `rex-library/<category>/`). Stores never hot-link Unsplash.
 *   - `url`      → 1600px-wide JPEG (q80); `width`/`height` are the stored file's real size.
 *   - `thumbUrl` → 480px-wide JPEG for pickers and grids.
 *
 * Licence: the Unsplash License (https://unsplash.com/license) allows free commercial and non-commercial use, with
 * no permission or attribution needed. It does not allow selling the photos unaltered or using them to build a
 * competing photo service. We still credit every photographer (`credit`) — show it in pickers where there is room.
 * docs/rex-photo-library.md lists every photo and photographer for our licence records.
 *
 * Adding photos:
 *   1. Find a free (non-Plus) photo on Unsplash and record the download (Unsplash API `download_location`, or the
 *      Unsplash MCP `download_asset` tool).
 *   2. Store `<id>.jpg` (w=1600, fm=jpg, q=80) and `<id>-480.jpg` (w=480) at
 *      `shopinbos-media/rex-library/<category>/` and check both public URLs return 200.
 *   3. Add an entry below (alt in short plain English; utm_source=shopinbos&utm_medium=referral on Unsplash links),
 *      add a row to docs/rex-photo-library.md, and run `node --test tests/rex-photo-library.test.mjs`.
 *
 * Pure data and helpers — no imports, safe on the server, in the browser and in tests.
 */

