/** Every photo, or just one category's, in library order. */
export function rexLibrary(category?: RexLibraryCategory): RexLibraryPhoto[] {
  return category ? REX_PHOTO_LIBRARY.filter((photo) => photo.category === category) : REX_PHOTO_LIBRARY.slice();
}

/** Categories that suit any store, added after the seller's own. */
const GENERAL_CATEGORIES: RexLibraryCategory[] = ["people", "backgrounds", "markets"];

/** Words in a "What do you sell?" answer → the library category that fits it. First match wins. */
const SELL_CATEGORY_RULES: Array<[RegExp, RexLibraryCategory]> = [
  [/hair|beauty|wig|braid|skin|make ?up|cosmetic|salon|spa|nail|perfume/, "hair_beauty"],
  [/gadget|phone|electronic|laptop|computer|tech|accessor/, "gadgets"],
  [/home|kitchen|decor|furniture|interior|household/, "home"],
  [/food|drink|snack|bak|cake|grocer|restaurant|catering|chops|juice/, "food"],
  [/fashion|cloth|wear|shoe|bag|fabric|textile|ankara|tailor|jewel|boutique/, "fashion"],
];

/**
 * The library categories for a seller's "What do you sell?" answers (e.g. "Hair and beauty", "Fashion", "Food",
 * "Gadgets", "Home", "Other", or the marketplace's own names like "Phones and gadgets"), most relevant first, with
 * people, backgrounds and markets always appended. Unknown answers and "Other" add nothing of their own.
 */
export function rexLibraryCategoriesFor(sellCategories: readonly string[]): RexLibraryCategory[] {
  const picked: RexLibraryCategory[] = [];
  const add = (category: RexLibraryCategory) => {
    if (!picked.includes(category)) picked.push(category);
  };
  for (const raw of sellCategories) {
    const name = String(raw ?? "").toLowerCase().replace(/&/g, " and ").replace(/[_-]+/g, " ").trim();
    if (!name) continue;
    const direct = REX_LIBRARY_CATEGORIES.find((category) => category.replace(/_/g, " ") === name);
    if (direct) {
      add(direct);
      continue;
    }
    const rule = SELL_CATEGORY_RULES.find(([pattern]) => pattern.test(name));
    if (rule) add(rule[1]);
  }
  for (const category of GENERAL_CATEGORIES) add(category);
  return picked;
}

/** The photos for a seller's "What do you sell?" answers: their own categories first, then people, backgrounds, markets. */
export function rexLibraryFor(sellCategories: readonly string[]): RexLibraryPhoto[] {
  return rexLibraryCategoriesFor(sellCategories).flatMap((category) => rexLibrary(category));
}
